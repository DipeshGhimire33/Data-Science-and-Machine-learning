# BASIC DATA TYPES in python are:
# 1. Numeric Data Types ==> integer, float
# 2. String Data Types
# 3. Boolean Data Types
# 4. List Data Types
# 5. Tuple Data Types
# 6. Set Data Types
# 7. Dictionary Data Types
# 8. None Data Type


print(5)
print(5.5)
print("Hello, World!")
print(True)
print([1, 2, 3])
print((1, 2, 3))
print({1, 2, 3})
print({"name": "Dipesh", "age": 25})
print(None)

# MORE DATA TYPES in python are:
# 9. Complex Data Type
# 10. Range Data Type
# 11. Bytes Data Type
# 12. Bytearray Data Type
# 13. Memoryview Data Type
# 14. Frozenset Data Type
# 15. Type Data Type
# 16. Module Data Type
# 17. Function Data Type
# 18. Class Data Type
# 19. Method Data Type
# 20. File Data Type ,etc.

print(1 + 2j)  # Complex Data Type
print(range(5))  # Range Data Type
print(b"Hello")  # Bytes Data Type
print(bytearray(b"Hello"))  # Bytearray Data Type
print(memoryview(b"Hello"))  # Memoryview Data Type
print(frozenset([1, 2, 3]))  # Frozenset Data Type
print(type(5))  # Type Data Type
print(__import__("math"))  # Module Data Type
print(len)  # Function Data Type
print(int)  # Class Data Type
print(str.upper)  # Method Data Type
print(open("file.txt", "w"))  # File Data Type
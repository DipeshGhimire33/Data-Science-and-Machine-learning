# Introduction to conditional statements.

# 1. If statement

number = 10

if number > 5:
    print("Number is greater than 5")


# 2. If-else statement

if number % 2 == 0:
    print("Number is even")
else:
    print("Number is odd")


# 3. If-elif-else statement

if number > 0:
    print("Number is positive")
elif number < 0:
    print("Number is negative")
else:
    print("Number is zero")
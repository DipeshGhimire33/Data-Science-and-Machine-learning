# Basic built-in data types in Python.

# 1. Numeric data types
print(5)              # int
print(5.5)            # float
print(1 + 2j)         # complex


# 2. String data type
print("Hello, World!")


# 3. Boolean data type
print(True)


# 4. List data type
print([1, 2, 3])


# 5. Tuple data type
print((1, 2, 3))


# 6. Set data type
print({1, 2, 3})


# 7. Dictionary data type
print({"name": "Dipesh", "age": 25})


# 8. None data type
print(None)


# 9. Range data type
print(range(5))


# 10. Bytes data type
print(b"Hello")


# 11. Bytearray data type
print(bytearray(b"Hello"))


# 12. Memoryview data type
print(memoryview(b"Hello"))


# 13. Frozenset data type
print(frozenset([1, 2, 3]))